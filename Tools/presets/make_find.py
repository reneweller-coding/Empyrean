"""The presets as the search by example compares them: per preset its four measures (work/presets/descriptors.json:
brightness, motion, width, noise) as features -- the motion on a log scale, where it is spread -- each centred on the
bank's mean and scaled by its spread, so that no measure outweighs the others. Writes Core/src/Find.inc, in the
bank's order.

    python make_find.py
"""
import json
import math
import pathlib

import make_presets

ROOT = pathlib.Path(__file__).resolve().parents[2]
DESCRIPTORS = ROOT / "work" / "presets" / "descriptors.json"
OUT = ROOT / "Core" / "src" / "Find.inc"


def raw(d):
    """A description's features before scaling: brightness, log motion, width, noise."""
    return [d[0], math.log(max(d[1], 0.0) + 0.01), d[2], d[3]]


def main():
    desc = json.loads(DESCRIPTORS.read_text(encoding="utf-8"))
    bank = make_presets.build()
    rows = [raw(desc[name]) for name, *_ in bank]
    n = len(rows)
    mean = [sum(r[k] for r in rows) / n for k in range(4)]
    spread = [math.sqrt(sum((r[k] - mean[k]) ** 2 for r in rows) / n) or 1.0 for k in range(4)]
    lines = ["// Generated by Tools/presets/make_find.py -- do not edit; edit the script and run it again.",
             "/// The features' centre: brightness, log(motion + 0.01), width, noise over the bank.",
             "constexpr float FindMean[4] = { " + ", ".join(f"{x:.6f}f" for x in mean) + " };",
             "/// And their spread (one standard deviation).",
             "constexpr float FindSpread[4] = { " + ", ".join(f"{x:.6f}f" for x in spread) + " };",
             "/// Every preset's features, centred and scaled, in the bank's order.",
             "const float FindFeatures[][4] = {"]
    for r in rows:
        lines.append("    { " + ", ".join(f"{(r[k] - mean[k]) / spread[k]:.4f}f" for k in range(4)) + " },")
    lines.append("};")
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"{n} presets -> {OUT}")


if __name__ == "__main__":
    main()
