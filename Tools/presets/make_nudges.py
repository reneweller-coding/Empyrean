"""The nudges and the focus from the sensitivity measure (additiv_presets --sensitivity -> work/presets/sensitivity.jsonl):
per shaping knob the mean change of each measure for its whole travel, over the presets in which it is heard -- its
group's gate open. The gates are written with it, so that the instrument knows when a knob is heard (Focus.h).

    python make_nudges.py
"""
import json
import math
import pathlib
import statistics

import make_journeys
import make_presets

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / "work" / "presets" / "sensitivity.jsonl"
DESCRIPTORS = ROOT / "work" / "presets" / "descriptors.json"
LEVELS = ROOT / "work" / "presets" / "levels.json"
OUT = ROOT / "Core" / "src" / "Nudges.inc"

# A knob is heard while any of its gates is not nought (a choice's first entry is its Off).
GATES = {
    "air_center": ["air"], "air_width": ["air"], "air_jitter": ["air"],
    "motion_rate": ["motion"], "motion_depth": ["motion"],
    "field_strength": ["field_mode"],
    "life_depth": ["life_mode"], "life_rate": ["life_mode"],
    "sync_coupling": ["sync_depth"], "sync_rate": ["sync_depth"],
    "cutoff": ["filter_model"], "resonance": ["filter_model"], "filter_env": ["filter_model"],
    "comb_sweep": ["comb_depth"],
}


def values_of(table, params):
    """A preset's knobs (its text) over the defaults."""
    v = {k: spec[3] for k, spec in table.items()}
    for kv in params.split():
        k, x = kv.split("=", 1)
        v[k] = float(x)
    return v


def heard(key, v):
    gates = GATES.get(key, [])
    return not gates or any(abs(v.get(g, 0.0)) > 1e-6 for g in gates)


def main():
    table = make_journeys.param_table()
    bank = {name: params for name, _, params, _ in make_presets.build()}
    rows = [json.loads(line) for line in DATA.read_text(encoding="utf-8").splitlines() if line.strip()]
    keys = list(rows[0]["d"].keys())
    sens, count = {}, {}
    for k in keys:
        ds = [r["d"][k][:5] for r in rows if heard(k, values_of(table, bank[r["preset"]]))]
        count[k] = len(ds)
        sens[k] = [statistics.fmean(d[m] for d in ds) if ds else 0.0 for m in range(5)]
    desc = json.loads(DESCRIPTORS.read_text(encoding="utf-8"))
    levels = json.loads(LEVELS.read_text(encoding="utf-8"))
    spread = [statistics.pstdev(d[m] for d in desc.values()) for m in range(4)] + [statistics.pstdev(levels.values())]
    lines = ["// Generated by Tools/presets/make_nudges.py -- do not edit; edit the script and run it again.",
             f"// From {len(rows)} presets of work/presets/sensitivity.jsonl.",
             "/// The measures' spread over the bank: brightness (octaves), motion, width, noise, level (dB).",
             "constexpr float MeasureSpreads[5] = { " + ", ".join(f"{s:.6f}f" for s in spread) + " };",
             "/// Per shaping knob: its key, its gates (heard while any is not nought; none: always), its sensitivity",
             "/// per measure for its whole travel, and in how many of the measured presets it was heard.",
             "const NudgeKnob NudgeKnobs[] = {"]
    for k in keys:
        g = GATES.get(k, [])
        gate = ", ".join(f'"{x}"' for x in g) if g else ""
        lines.append(f'    {{ "{k}", {{ {gate} }}, {{ ' + ", ".join(f"{x:.5f}f" for x in sens[k]) + f" }}, {count[k]} }},")
    lines.append("};")
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"{len(keys)} knobs from {len(rows)} presets -> {OUT}")
    # The strongest per measure, for a look.
    for m, name in enumerate(["brightness", "motion", "width", "noise", "level"]):
        top = sorted(keys, key=lambda k: -abs(sens[k][m]) / (spread[m] or 1.0))[:6]
        print(f"  {name:10s}", ", ".join(f"{k} {sens[k][m] / (spread[m] or 1.0):+.2f}" for k in top))


if __name__ == "__main__":
    main()
