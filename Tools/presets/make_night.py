"""make_night.py: what the night director (Core/include/additiv/NightDirector.h) needs of the bank -- into
Core/src/NightDirector.inc.

The director composes a night along a curve of stillness and brightness and keeps every glide gentle; the
brightness and the four measures its distance is made of are compiled in already (Find.inc). What only this side has
is the part of the presets' parameters (make_journeys.py, 19./20.11.2026):

  stillness   the stillness a group's Night is chosen by (make_journeys.measures()) without its brightness, which is
              the curve's other axis: of the rest's weights (four tenths the measured motion, one the noise, three the
              parameters' stillness -- the motion, shimmer, ripple and sync, the slowest attacks, the slowest
              conductor) 0.5 the measured motion, 0.125 the noise, 0.375 the parameters; lower is stiller. (With the
              brightness counted in it too, the stillness and the brightness of a night moved as one: in a prototype
              over nine nights the measured motion alone followed the curve with a Spearman of 0.01 on average,
              without it 0.32; the stillness itself 0.98 either way.)
  moving      how much a preset moves by itself, half measured, half set (the conductor's pace and the figures do not
              show in a chord of fourteen seconds) -- what make_journeys.timings() makes a stay's length of

Both per preset in the bank's order, as z-scores (three decimals: the director ranks them). And the families of groups
the shipped Whole Nights draw from (WHOLE_NIGHTS), the director's choices beside "all of them" and "the whole bank",
and the groups the morning draws from as well (the dawn).

    python Tools/presets/make_night.py
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import make_journeys  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "Core" / "src" / "NightDirector.inc"
MORNING_GROUPS = ["Dawn Choruses"]   # the plan's dawn: brighter and a little more moving over the last half hour


def main():
    bank, groups, _points, mz, moving, _still, pstill = make_journeys.measures()
    still = {n: (0.5 * mz[n][1] + 0.125 * mz[n][3] + 0.375 * pstill[n]) if n in mz else pstill[n] for n, *_ in bank}
    for g in MORNING_GROUPS:
        if g not in groups:
            raise SystemExit(f"no group {g}")
    lines = ["// Generated by Tools/presets/make_night.py -- do not edit; edit the script and run it again.",
             "/// Per preset, in the bank's order: its stillness without its brightness (lower is stiller) and how much",
             "/// it moves by itself (higher moves more), from Tools/presets/make_journeys.py's measures (z-scores).",
             "const float NightMeasures[][2] = {"]
    for name, *_ in bank:
        lines.append(f"    {{ {still[name]:.3f}f, {moving[name]:.3f}f }},")
    lines += ["};",
              "/// The families of groups the shipped Whole Nights draw from: a name, its groups with '|' between them.",
              "const char *const NightFamilies[][2] = {"]
    for title, family in make_journeys.WHOLE_NIGHTS:
        for g in family:
            if g not in groups:
                raise SystemExit(f"{title}: no group {g}")
        lines.append(f'    {{ "{title.replace("Whole Night - ", "")}", "{"|".join(family)}" }},')
    lines += ["};",
              "/// The groups a night's morning draws from besides the family chosen (the dawn).",
              "const char *const NightMorningGroups[] = { " + ", ".join(f'"{g}"' for g in MORNING_GROUPS) + " };"]
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"{len(bank)} presets, {len(make_journeys.WHOLE_NIGHTS)} families -> {OUT}")


if __name__ == "__main__":
    main()
